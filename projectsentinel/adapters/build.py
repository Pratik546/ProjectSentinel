"""Build-validation evidence adapters; they inspect logs and never run builds."""
from __future__ import annotations

import json
import re
from pathlib import Path

from ..models import Confidence, FileRecord, Finding, Severity
from ._common import make_finding
from .types import BuildValidationResult

UNITY_LOG_NAMES = {"editor.log", "build.log", "buildreport.json", "build-report.json", "unitybuild.log"}
UNREAL_LOG_NAMES = {"packaging.log", "build.log", "unrealbuild.log", "automationtool.log"}
FAILURE = re.compile(r"(?i)\b(?:build\s+failed|build failed|buildfailure|packagingresults:\s*error|fatal error|fatal:|exitcode\s*[=:]\s*[1-9]|error\s*:\s*|error\s+[A-Za-z0-9_.-]+\s*:)")
SUCCESS = re.compile(r"(?i)\b(?:build\s+succeeded|build succeeded|build completed|buildresult\s*[=:]\s*(?:succeeded|success)|exitcode\s*[=:]\s*0|build successful)\b")


def _is_log(record: FileRecord) -> bool:
    name = Path(record.path).name.lower()
    return name in UNITY_LOG_NAMES | UNREAL_LOG_NAMES or name.endswith((".log", ".buildlog", ".buildreport")) or (name.endswith(".txt") and any(token in name for token in ("build", "log", "packag")))


def _engine(files: list[FileRecord]) -> str:
    paths = {record.path.replace("\\", "/") for record in files}
    if any(path.lower().endswith(".uproject") or path.lower().endswith(".uplugin") for path in paths):
        return "Unreal Engine"
    if "Packages/manifest.json" in paths or any(path.startswith("ProjectSettings/") for path in paths):
        return "Unity"
    return ""


def _report_evidence(record: FileRecord, engine: str) -> tuple[bool | None, int | None, str | None, dict[str, object]]:
    text = record.text or ""
    lines = text.splitlines()
    failures = [(index, line.strip()) for index, line in enumerate(lines, 1) if FAILURE.search(line)]
    successes = [(index, line.strip()) for index, line in enumerate(lines, 1) if SUCCESS.search(line)]
    metadata: dict[str, object] = {"engine": engine, "failure_lines": len(failures), "success_lines": len(successes)}
    # BuildReport JSON is evidence generated by Unity, but parsing it is still
    # not the same as validating a build or executing its output.
    if Path(record.path).suffix.lower() == ".json" and "buildreport" in Path(record.path).name.lower():
        try:
            report = json.loads(text)
            if isinstance(report, dict):
                summary = report.get("summary") if isinstance(report.get("summary"), dict) else report
                result = str(summary.get("result", "")).lower()
                if result in {"succeeded", "success", "0"}:
                    successes.append((1, f"BuildReport result: {result}"))
                elif result in {"failed", "failure", "1"}:
                    failures.append((1, f"BuildReport result: {result}"))
                metadata["report_result"] = result or None
        except (json.JSONDecodeError, TypeError):
            metadata["report_parse_error"] = True
    if failures:
        return False, failures[0][0], failures[0][1], metadata
    if successes:
        return True, successes[0][0], successes[0][1], metadata
    return None, None, None, metadata


def validate_build_evidence(files: list[FileRecord]) -> BuildValidationResult:
    engine = _engine(files)
    if not engine:
        return BuildValidationResult(adapter="build", state="not_applicable", engine="")
    logs = [record for record in files if _is_log(record) and record.text]
    relevant = [
        record
        for record in logs
        if engine == "Unity"
        or Path(record.path).name.lower() in UNREAL_LOG_NAMES
        or (Path(record.path).suffix.lower() == ".log" and (FAILURE.search(record.text or "") or SUCCESS.search(record.text or "")))
        or any(token.lower() in (record.text or "").lower() for token in ("AutomationTool", "PackagingResults", "LogInit", "UnrealBuildTool"))
    ]
    findings: list[Finding] = []
    if not relevant:
        findings.append(
            make_finding(
                "BUILD-EVIDENCE-MISSING",
                f"{engine} build evidence is not present",
                Severity.INFO,
                "",
                f"Detected {engine}, but no recognizable build report or build log was included in the bounded scan. No build result is claimed.",
                module="SceneSentry",
                confidence=Confidence.HIGH,
                actionable=False,
                remediation="Provide a release build report or log as evidence, then validate the actual build with the engine toolchain.",
                metadata={"engine": engine, "evidence_status": "missing"},
            )
        )
        return BuildValidationResult(adapter="build", state="inspected", findings=findings, engine=engine, log_paths=(), passed=None, limitations=["No build command was executed; absence of a log is not evidence of a failed build."])

    paths: list[str] = []
    passed_values: list[bool] = []
    for record in relevant:
        paths.append(record.path)
        passed, line_no, evidence, metadata = _report_evidence(record, engine)
        if passed is not None:
            passed_values.append(passed)
        if passed is False:
            findings.append(
                make_finding(
                    "BUILD-FAILURE-EVIDENCE",
                    f"{engine} build failure evidence found",
                    Severity.HIGH,
                    record.path,
                    "A build or packaging log contains failure evidence. This does not establish the root cause beyond the retained log line.",
                    line=line_no,
                    evidence=evidence,
                    module="SceneSentry",
                    confidence=Confidence.HIGH,
                    remediation="Reproduce the release build with the engine's normal toolchain, resolve the reported failure, and retain the successful build receipt.",
                    metadata={**metadata, "evidence_status": "failed"},
                )
            )
        elif passed is True:
            findings.append(
                make_finding(
                    "BUILD-SUCCESS-EVIDENCE",
                    f"{engine} build success evidence found",
                    Severity.INFO,
                    record.path,
                    "A build report or log contains a success marker. This is evidence from the artifact, not an independently validated build.",
                    line=line_no,
                    evidence=evidence,
                    module="SceneSentry",
                    confidence=Confidence.MEDIUM,
                    actionable=False,
                    metadata={**metadata, "evidence_status": "success", "claims": []},
                )
            )
        else:
            findings.append(
                make_finding(
                    "BUILD-EVIDENCE-INCONCLUSIVE",
                    f"{engine} build log has no conclusive result",
                    Severity.INFO,
                    record.path,
                    "A recognized build artifact was found, but it contains neither a supported success nor failure marker.",
                    module="SceneSentry",
                    confidence=Confidence.HIGH,
                    actionable=False,
                    metadata={"engine": engine, "evidence_status": "inconclusive"},
                )
            )
    passed = False if False in passed_values else (True if passed_values and all(passed_values) else None)
    return BuildValidationResult(
        adapter="build",
        state="inspected",
        findings=findings,
        evidence={"engine": engine, "logs": paths, "passed": passed},
        engine=engine,
        log_paths=tuple(paths),
        passed=passed,
        limitations=["No build, compiler, linker, cooker, signer, or packaged executable was executed or independently validated."],
    )


def analyze(files: list[FileRecord]) -> list[Finding]:
    return validate_build_evidence(files).findings


def validate_unity_build(files: list[FileRecord]) -> BuildValidationResult:
    result = validate_build_evidence(files)
    if result.engine in {"", "Unity"}:
        return result
    return BuildValidationResult(adapter="build.unity", state="not_applicable", engine="Unity")


def validate_unreal_build(files: list[FileRecord]) -> BuildValidationResult:
    result = validate_build_evidence(files)
    if result.engine in {"", "Unreal Engine"}:
        return result
    return BuildValidationResult(adapter="build.unreal", state="not_applicable", engine="Unreal Engine")
